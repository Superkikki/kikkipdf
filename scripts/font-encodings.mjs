import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { Font, FontNames } = require('@pdf-lib/standard-fonts');
const source = await readFile('node_modules/pdfjs-dist/legacy/build/pdf.worker.mjs', 'utf8');
const encodings = {};
for (const name of ['StandardEncoding', 'WinAnsiEncoding', 'MacRomanEncoding', 'MacExpertEncoding', 'SymbolSetEncoding', 'ZapfDingbatsEncoding']) {
  const match = source.match(new RegExp(`const ${name} = (\\[[^\\n]+\\]);`));
  if (!match) throw Error(`Missing encoding: ${name}`);
  encodings[name] = JSON.parse(match[1]);
}
const glyphs = {};
for (const name of ['getGlyphsUnicode', 'getDingbatsGlyphsUnicode']) {
  const start = source.indexOf(`const ${name} = getLookupTableFactory(function (t) {`);
  if (start < 0) throw Error(`Missing glyph table: ${name}`);
  const end = source.indexOf('\n});', start);
  for (const match of source.slice(start, end).matchAll(/t\.([\w]+) = (0x[\da-fA-F]+|\d+);/g))
    glyphs[match[1]] = Number(match[2]);
}
if (Object.keys(glyphs).length < 4000) throw Error('Incomplete glyph table');
const widths = {};
for (const name of Object.values(FontNames))
  widths[name] = Object.fromEntries(Font.load(name).CharMetrics.map(({N, WX}) => [N, WX]));
await writeFile('src/direct/fontTables.ts', '// Generated by scripts/font-encodings.mjs; PDF.js Apache-2.0, standard-fonts MIT.\nexport default ' + JSON.stringify({ encodings, glyphs, widths }) + ' as { encodings: Record<string, string[]>; glyphs: Record<string, number>; widths: Record<string, Record<string, number>> };\n');
