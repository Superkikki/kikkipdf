import { test, expect } from "@playwright/test";
import { PDFDocument, PDFName, PDFString } from "pdf-lib";
import { readFile } from "node:fs/promises";
import { layerGroupIds, readLayerOrder } from "../../src/layers/pdfOrder";
import { openProject } from "../../src/state/project";

test("organizes layers with headings, undo, project/PDF save and reopen", async ({ page }, info) => {
  const pdf = await PDFDocument.create(); pdf.addPage();
  const groups = ["A", "B"].map(name => pdf.context.register(pdf.context.obj({ Type: "OCG", Name: PDFString.of(name) })));
  pdf.catalog.set(PDFName.of("OCProperties"), pdf.context.obj({ OCGs: groups, D: { Order: groups, OFF: [groups[1]], Locked: [groups[0]] } }));
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/"); await page.keyboard.press("Escape");
  let chooser = page.waitForEvent("filechooser"); await page.getByRole("button", { name: "PDFを開く", exact: true }).click();
  await (await chooser).setFiles({ name: "order.pdf", mimeType: "application/pdf", buffer: Buffer.from(await pdf.save()) });
  await page.getByRole("button", { name: "レイヤー", exact: true }).click();
  const panel = page.locator(".layer-panel"), editor = panel.locator(".layer-order-editor");
  await editor.locator("summary").click(); await editor.getByRole("button", { name: "見出しを作成", exact: true }).click();
  await page.getByLabel("見出し名", { exact: true }).fill("資料");
  await page.getByRole("dialog").getByRole("button", { name: "適用", exact: true }).click();
  const selection = panel.getByLabel("order.pdfの編集するレイヤー項目", { exact: true }), parent = panel.getByLabel("order.pdfの移動先の見出し", { exact: true });
  const heading = await selection.inputValue();
  await editor.getByRole("button", { name: "上へ", exact: true }).click(); await editor.getByRole("button", { name: "上へ", exact: true }).click();
  await selection.selectOption(`group:${groups[1].objectNumber}R`); await parent.selectOption(heading);
  await expect(panel.getByRole("checkbox", { name: "B", exact: true })).not.toBeChecked();
  await expect(panel.getByRole("checkbox", { name: "A", exact: true })).toBeDisabled();
  await page.getByTitle("元に戻す (Ctrl+Z)", { exact: true }).click(); await expect(parent).toHaveValue("");
  await page.getByTitle("やり直す (Ctrl+Y)", { exact: true }).click(); await expect(parent).toHaveValue(heading);
  let download = page.waitForEvent("download"); await page.locator("summary").filter({ hasText: "ファイル" }).click();
  await page.getByRole("button", { name: "編集プロジェクトを保存", exact: true }).click();
  const project = info.outputPath("order.kpdf"); await (await download).saveAs(project);
  const restored = await openProject(new Uint8Array(await readFile(project)));
  expect(Object.values(restored.sources)[0].layerOrder![0].title).toBe("資料");
  download = page.waitForEvent("download"); await page.getByRole("button", { name: "保存", exact: true }).click();
  const file = info.outputPath("order.pdf"); await (await download).saveAs(file);
  const saved = await PDFDocument.load(await readFile(file)), order = readLayerOrder(saved, new Set(layerGroupIds(saved)));
  expect(order[0].title).toBe("資料"); expect(order[0].children).toHaveLength(1); expect(order).toHaveLength(2);
  await page.reload(); chooser = page.waitForEvent("filechooser"); await page.getByRole("button", { name: "PDFを開く", exact: true }).click(); await (await chooser).setFiles(file);
  await page.getByRole("button", { name: "レイヤー", exact: true }).click(); await expect(panel).toContainText("資料");
  await panel.locator(".layer-order-editor summary").click();
  await panel.getByLabel("order.pdfの編集するレイヤー項目", { exact: true }).selectOption("heading:1");
  await panel.getByRole("button", { name: "見出しだけを削除", exact: true }).click();
  await expect(panel.locator(".layer-heading")).toHaveCount(0);
  expect(errors).toEqual([]);
});
