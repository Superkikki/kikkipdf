test("switches registered text between directions, wraps vertically by height and restores the project", async ({ page }, info) => {
  const d = emptyDocument("vertical-layout.pdf"); d.pages = [blankPage()];
  d.pages[0].objects = [{ ...newObject("text", 200, 40), text: "ABCDEF", fontSize: 20, width: 180, height: 40 }];
  await page.goto("/"); let chooser = page.waitForEvent("filechooser");
  await page.getByRole("button", { name: "PDFを開く", exact: true }).click();
  await (await chooser).setFiles({ name: "vertical-layout.kpdf", mimeType: "application/zip", buffer: Buffer.from(await saveProject(d)) });
  const overlay = page.locator(".viewer-scroll .editable-text[data-layout-ready=true]"); await expect(overlay).toBeVisible();
  await page.locator(".viewer-scroll .object-layer > g").first().click();
  chooser = page.waitForEvent("filechooser"); await page.getByRole("button", { name: "フォントを追加", exact: true }).click();
  await (await chooser).setFiles("public/assets/pdfjs/standard_fonts/LiberationSans-Regular.ttf");
  await expect(overlay).toHaveAttribute("font-family", /^Kikki/);
  const fontId = await page.getByLabel("フォント", { exact: true }).inputValue();
  await page.getByLabel("文字の方向").selectOption("vertical"); await expect(overlay.locator("use")).toHaveCount(6);
  await expect(page.getByLabel("フォント", { exact: true })).toHaveValue(fontId);
  await expect(page.getByRole("button", { name: "太字", exact: true })).toBeDisabled();
  await page.getByLabel("height", { exact: true }).fill("40"); await page.getByLabel("高さに合わせて折り返す", { exact: true }).check();
  await expect(page.locator(".text-layout-summary")).toContainText("3 列");
  await page.getByRole("button", { name: "文字に合わせて幅を調整", exact: true }).click();
  await expect(page.getByLabel("width", { exact: true })).toHaveValue("70");
  await expect(page.getByLabel("x", { exact: true })).toHaveValue("150");
  await page.getByLabel("文字の方向").selectOption("horizontal"); await expect(overlay.locator("tspan")).toHaveCount(1);
  await page.getByLabel("文字の方向").selectOption("vertical"); await expect(overlay.locator("use")).toHaveCount(6);
  let download = page.waitForEvent("download"); await page.locator("summary").filter({ hasText: "ファイル" }).click();
  await page.getByRole("button", { name: "編集プロジェクトを保存", exact: true }).click();
  const project = info.outputPath("vertical-layout.kpdf"); await (await download).saveAs(project);
  const restored = await openProject(new Uint8Array(await readFile(project)));
  expect(restored.pages[0].objects[0].writingMode).toBe("vertical"); expect(restored.pages[0].objects[0].fontId).toBe(fontId);
  download = page.waitForEvent("download"); await page.getByRole("button", { name: "保存", exact: true }).click();
  const pdf = info.outputPath("vertical-custom.pdf"); await (await download).saveAs(pdf);
  expect((await inspectDirectText(new Uint8Array(await readFile(pdf)), 0)).runs.map(r => r.text)).toEqual(["ABCDEF"]);
});
