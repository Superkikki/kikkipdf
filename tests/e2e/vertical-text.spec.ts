import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import fontkit from "@pdf-lib/fontkit";
import { PDFArray, PDFDict, PDFDocument, PDFName } from "pdf-lib";
import { blankPage, emptyDocument, newObject } from "../../src/state/model";
import { saveProject, openProject } from "../../src/state/project";
import { inspectDirectText } from "../../src/direct/content";
async function fixture(downstream = false) {
  const pdf = await PDFDocument.create(); pdf.registerFontkit(fontkit);
  const p = pdf.addPage([420, 595]);
  const font = await pdf.embedFont(await readFile("public/assets/NotoSansJP-Regular.otf"), { subset: false });
  const following = font.encodeText("後続").toString();
  const first = font.encodeText("日本語の縦書き").toString(), second = font.encodeText("隣の列").toString();
  await pdf.flush();
  const dict = pdf.context.lookup(font.ref, PDFDict); dict.set(PDFName.of("Encoding"), PDFName.of("Identity-V"));
  dict.lookup(PDFName.of("DescendantFonts"), PDFArray).lookup(0, PDFDict).set(PDFName.of("DW2"), pdf.context.obj([880, -1000]));
  p.node.set(PDFName.of("Resources"), pdf.context.obj({ Font: { F1: font.ref } }));
  p.node.set(PDFName.of("Contents"), pdf.context.register(pdf.context.flateStream(`BT /F1 20 Tf ${downstream ? "80 Tz 2 Tc 3 Ts" : ""} 1 0 0 1 300 520 Tm ${downstream ? `[${first} 125] TJ /F1 14 Tf ${following} Tj /F1 20 Tf` : `${first} Tj`} 1 0 0 1 260 520 Tm ${second} Tj ET`)));
  return Buffer.from(await pdf.save());
}
test("vertical source editing preserves neighbour, previews alternate glyphs, and saves an editable Identity-V PDF", async ({ page }, info) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  const chooser = page.waitForEvent("filechooser"); await page.getByRole("button", { name: "PDFを開く", exact: true }).click();
  await (await chooser).setFiles({ name: "vertical.pdf", mimeType: "application/pdf", buffer: await fixture() });
  await expect(page.locator(".viewer-scroll .page-view[data-rendered=true]")).toBeVisible();
  const original = page.locator(".viewer-scroll .textLayer span").filter({ hasText: /^日本語の縦書き$/ });
  const neighbour = page.locator(".viewer-scroll .textLayer span").filter({ hasText: /^隣の列$/ });
  await expect(original).toBeVisible(); const before = await neighbour.boundingBox();
  await page.getByRole("button", { name: "ツール", exact: true }).click();
  await page.getByRole("button", { name: "既存文字", exact: true }).click(); await original.dblclick();
  await expect(page.getByLabel("文字の方向")).toHaveValue("vertical");
  await page.getByLabel("テキスト内容").fill("変更、。「」ー");
  const overlay = page.locator(".viewer-scroll .editable-text[data-layout-ready=true]");
  await expect(overlay).toHaveText("変更、。「」ー"); await expect(overlay.locator("use")).toHaveCount(7);
  await expect(original).toHaveCount(0); const after = await neighbour.boundingBox();
  expect(after!.x).toBeCloseTo(before!.x, 1); expect(after!.y).toBeCloseTo(before!.y, 1);
  await page.getByRole("button", { name: /^元に戻す/ }).click(); await page.getByRole("button", { name: /^元に戻す/ }).click();
  await expect(original).toHaveCount(1); await page.getByRole("button", { name: /^やり直す/ }).click(); await page.getByRole("button", { name: /^やり直す/ }).click();
  await expect(overlay).toHaveText("変更、。「」ー");
  const download = page.waitForEvent("download"); await page.getByRole("button", { name: "保存", exact: true }).click();
  const path = info.outputPath("vertical-saved.pdf"); await (await download).saveAs(path);
  const saved = await readFile(path); const runs = (await inspectDirectText(new Uint8Array(saved), 0)).runs;
  expect(runs.map(r => r.text)).toContain("変更、。「」ー"); expect(runs.map(r => r.text)).not.toContain("日本語の縦書き");
  await page.reload();
  const reopen = page.waitForEvent("filechooser"); await page.getByRole("button", { name: "PDFを開く", exact: true }).click();
  await (await reopen).setFiles({ name: "vertical-saved.pdf", mimeType: "application/pdf", buffer: saved });
  const replacement = page.locator(".viewer-scroll .textLayer span").filter({ hasText: /^変更、。「」ー$/ });
  await expect(replacement).toBeVisible();
  await expect(page.locator(".viewer-scroll .page-view[data-rendered=true]")).toBeVisible();
  const pixels = await page.locator(".viewer-scroll canvas").first().evaluate((canvas: HTMLCanvasElement) => {
    const ctx = canvas.getContext("2d")!, sx = canvas.width / 420, sy = canvas.height / 595;
    return Array.from({ length: 7 }, (_, row) => {
      const data = ctx.getImageData(Math.floor(290 * sx), Math.floor((75 + row * 20) * sy), Math.ceil(20 * sx), Math.ceil(20 * sy)).data;
      let ink = 0; for (let i = 0; i < data.length; i += 4) if (data[i] < 128 && data[i + 1] < 128 && data[i + 2] < 128) ink++;
      return ink;
    });
  });
  expect(pixels.every(n => n > 0)).toBe(true);
  await page.getByRole("button", { name: "ツール", exact: true }).click(); await page.getByRole("button", { name: "既存文字", exact: true }).click();
  await replacement.dblclick(); await expect(page.getByLabel("テキスト内容")).toHaveValue("変更、。「」ー");
  expect(errors).toEqual([]);
});

